Write-VerboseMsg "Using patcher: $($patcher.Name) at $($patcher.Path)" -Color Cyan

$gameFolders = @()

# --- Auto-detect game libraries ---
Write-VerboseMsg "`nStep 2: Auto-detecting game libraries..." -Color Yellow

# Steam
Write-VerboseMsg "  [Scanning] Steam libraries..." -Color Gray
$steamFolders = @()
$regPath = "HKLM:\SOFTWARE\WOW6432Node\Valve\Steam"
$steamInstallPath = $null
try {
    $steamInstallPath = (Get-ItemProperty -Path $regPath -ErrorAction Stop).InstallPath
    if ($steamInstallPath) {
        $steamCommon = Join-Path $steamInstallPath "steamapps\common"
        if (Test-Path $steamCommon) { $steamFolders += $steamCommon }
    }
} catch { Write-VerboseMsg "    Steam not found in registry." -Color DarkYellow }

if ($steamInstallPath) {
    $vdfPath = Join-Path $steamInstallPath "steamapps\libraryfolders.vdf"
    if (Test-Path $vdfPath) {
        $vdfContent = Get-Content $vdfPath -Raw
        $matches = [regex]::Matches($vdfContent, '\\"path\\":\\"([^\\"]+)\\"')
        foreach ($match in $matches) {
            $commonPath = Join-Path $match.Groups[1].Value "steamapps\common"
            if (Test-Path $commonPath) { $steamFolders += $commonPath }
        }
    }
}
$steamFolders = $steamFolders | Select-Object -Unique
if ($steamFolders.Count -gt 0) {
    Write-VerboseMsg "`n  Steam libraries found:" -Color Cyan
    $steamFolders | ForEach-Object { Write-VerboseMsg "    - $_" -Color Gray }
    $includeSteam = Read-Host "  Include Steam folders in patching? (y/n, default: y)"
    if ($includeSteam -ne 'n') {
        $gameFolders += $steamFolders
        Write-VerboseMsg "  Steam folders added." -Color Green
    } else {
        Write-VerboseMsg "  Steam folders skipped." -Color DarkGray
    }
} else {
    Write-VerboseMsg "    No Steam libraries found." -Color DarkGray
}

# GOG
Write-VerboseMsg "`n  [Scanning] GOG libraries..." -Color Gray
$gogFolders = @()
$gogDefault = "C:\Program Files (x86)\GOG Galaxy\Games"
if (Test-Path $gogDefault) { $gogFolders += $gogDefault }
$gogRegPath = "HKLM:\SOFTWARE\WOW6432Node\GOG.com\Games"
if (Test-Path $gogRegPath) {
    $gogKeys = Get-ChildItem -Path $gogRegPath -ErrorAction SilentlyContinue
    foreach ($key in $gogKeys) {
        $gamePath = (Get-ItemProperty -Path $key.PSPath -ErrorAction SilentlyContinue).path
        if ($gamePath -and (Test-Path $gamePath)) { $gogFolders += $gamePath }
    }
}
$gogFolders = $gogFolders | Select-Object -Unique
if ($gogFolders.Count -gt 0) {
    Write-VerboseMsg "`n  GOG libraries found:" -Color Cyan
    $gogFolders | ForEach-Object { Write-VerboseMsg "    - $_" -Color Gray }
    $includeGOG = Read-Host "  Include GOG folders in patching? (y/n, default: n)"
    if ($includeGOG -eq 'y') {
        $gameFolders += $gogFolders
        Write-VerboseMsg "  GOG folders added." -Color Green
    } else {
        Write-VerboseMsg "  GOG folders skipped." -Color DarkGray
    }
} else {
    Write-VerboseMsg "    No GOG libraries found." -Color DarkGray
}

# Epic
Write-VerboseMsg "`n  [Scanning] Epic libraries..." -Color Gray
$epicFolders = @()
$epicDefault = "C:\Program Files\Epic Games"
if (Test-Path $epicDefault) { $epicFolders += $epicDefault }
$manifestPath = "$env:ProgramData\Epic\EpicGamesLauncher\Data\Manifests"
if (Test-Path $manifestPath) {
    $manifestFiles = Get-ChildItem -Path $manifestPath -Filter "*.item" -ErrorAction SilentlyContinue
    foreach ($file in $manifestFiles) {
        try {
            $manifestContent = Get-Content $file.FullName -Raw -ErrorAction Stop
            if ($manifestContent -match '"InstallLocation":\s*"([^"]+)"') {
                $installPath = $matches[1]
                if (Test-Path $installPath) { $epicFolders += $installPath }
            }
        } catch { }
    }
}
$epicFolders = $epicFolders | Select-Object -Unique
if ($epicFolders.Count -gt 0) {
    Write-VerboseMsg "`n  Epic libraries found:" -Color Cyan
    $epicFolders | ForEach-Object { Write-VerboseMsg "    - $_" -Color Gray }
    $includeEpic = Read-Host "  Include Epic folders in patching? (y/n, default: n)"
    if ($includeEpic -eq 'y') {
        $gameFolders += $epicFolders
        Write-VerboseMsg "  Epic folders added." -Color Green
    } else {
        Write-VerboseMsg "  Epic folders skipped." -Color DarkGray
    }
} else {
    Write-VerboseMsg "    No Epic libraries found." -Color DarkGray
}

# Additional custom folders
Write-VerboseMsg "`nDo you want to add any additional game folders (e.g., custom installations or other launchers)?" -Color Cyan
$addMore = Read-Host "Enter y/n (default: n)"
if ($addMore -eq 'y') {
    Write-VerboseMsg "Enter full folder paths (one per line). Type 'done' when finished:" -Color Yellow
    while ($true) {
        $path = Read-Host "Path"
        if ($path -eq 'done') { break }
        $path = Remove-Quotes $path
        if (Test-Path $path) {
            $gameFolders += $path
            Write-VerboseMsg "  Added: $path" -Color Green
        } else {
            Write-VerboseMsg "  Path not found: $path" -Color Red
        }
    }
}

# User-defined ignore patterns
$userPatterns = @()
Write-VerboseMsg "`nDo you want to specify folders or .exe names to skip?" -Color Cyan
$skipConfig = Read-Host "Enter y/n (default: n)"
if ($skipConfig -eq 'y') {
    Write-VerboseMsg "Enter patterns to ignore (e.g., 'Mods', 'Launcher.exe', 'bin'). One per line. Type 'done' when finished:" -Color Yellow
    while ($true) {
        $pattern = Read-Host "Ignore"
        if ($pattern -eq 'done') { break }
        if ($pattern -ne '') {
            $userPatterns += $pattern
            Write-VerboseMsg "  Will skip: $pattern" -Color DarkGray
        }
    }
}

$defaultExcludes = @(
    "_CommonRedist", "DotNet", "DirectX", "VCRedist", "EasyAntiCheat", "BattlEye",
    "AntiCheat", "steamapps\common\Steamworks Shared", "__Installer", "Support",
    "Redist", "Tools", "*backup*",
    "*unins*.exe", "*uninstall*.exe", "*Uninstall*.exe", "*remove*.exe", "*cleanup*.exe",
    "*setup*.exe", "*install*.exe", "*Installer*.exe", "*redist*.exe",
    "*dxsetup*.exe", "*dxwebsetup*.exe", "*vcredist*.exe", "*dotnet*.exe",
    "*oalinst*.exe", "*UE4PrereqSetup*.exe", "*EpicOnlineServicesInstaller*.exe",
    "*patcher*.exe", "*patch*.exe", "*updater*.exe", "*helper*.exe", "*service*.exe",
    "*crash*.exe", "*error*.exe", "*report*.exe", "*dump*.exe", "*bugsplat*.exe",
    "*UnityCrashHandler*.exe", "*BsSndRpt*.exe", "*BugSplat*.exe",
    "cgc.exe", "nvdxt.exe", "fxc.exe", "texconv.exe", "texassemble.exe",
    "QuickSFV.exe", "elevate.exe", "ffmpeg.exe", "webclient.exe", "winlive-webclient.exe"
)
$ignorePatterns = $defaultExcludes + $userPatterns

if ($gameFolders.Count -eq 0) {
    Write-VerboseMsg "No game folders selected! Exiting." -Color Red
    Read-Host "Press Enter to exit"
    exit 1
}

Write-VerboseMsg "`nTotal game folders to scan: $($gameFolders.Count)" -Color Cyan
$gameFolders | ForEach-Object { Write-VerboseMsg " - $_" -Color Gray }
Write-VerboseMsg "`nStep 3: Starting automatic LAA patching process..." -Color Cyan

# --- Scan and patch ---
$totalPatched = 0
$skippedList = @()
$failedList = @()
$backupCreatedCount = 0
$totalExeFilesFound = 0
$total32BitExeFiles = 0

foreach ($libraryPath in $gameFolders) {
    Write-VerboseMsg "`n=== Scanning: $libraryPath ===" -Color Yellow
    $allExes = Get-ChildItem -Path $libraryPath -Filter "*.exe" -Recurse -ErrorAction SilentlyContinue
    Write-VerboseMsg "Found $($allExes.Count) .exe files in this folder (including subfolders)." -Color Gray

    foreach ($exeFile in $allExes) {
        $exePath = $exeFile.FullName
        $totalExeFilesFound++
        Write-VerboseMsg "`n  [$totalExeFilesFound] Processing: $($exeFile.Name)" -Color White
        Write-VerboseMsg "    Full path: $exePath" -Color DarkGray

        # Check ignore patterns
        $shouldSkip = $false
        foreach ($pattern in $ignorePatterns) {
            if ($exePath -like "*$pattern*" -or $exeFile.Name -like $pattern) {
                $shouldSkip = $true
                Write-VerboseMsg "    ⚠ SKIPPED by pattern: $pattern" -Color DarkGray
                break
            }
        }
        if ($shouldSkip) {
            $skippedList += $exePath
            continue
        }

        # Architecture check
        Write-VerboseMsg "    Checking PE header architecture..." -Color Gray
        try {
            $peHeader = Get-Content $exePath -Encoding Byte -TotalCount 4096 -ErrorAction Stop
            $offset = [BitConverter]::ToInt32($peHeader, 0x3C) + 4
            $machine = [BitConverter]::ToUInt16($peHeader, $offset)
            Write-VerboseMsg "    Machine type code: 0x$($machine.ToString('X'))" -Color Gray
            if ($machine -eq 0x14C) {
                Write-VerboseMsg "    ✓ Architecture: 32-bit (eligible for LAA)" -Color Green
                $total32BitExeFiles++
            } elseif ($machine -eq 0x8664) {
                Write-VerboseMsg "    ✗ Architecture: 64-bit (LAA not needed/not applicable)" -Color DarkYellow
                $skippedList += $exePath
                continue
            } else {
                Write-VerboseMsg "    ? Unknown machine type: 0x$($machine.ToString('X')) - skipping" -Color DarkYellow
                $skippedList += $exePath
                continue
            }
        } catch {
            Write-VerboseMsg "    ⚠ WARNING: Could not read PE header: $_" -Color DarkRed
            Write-VerboseMsg "    Skipping this file to be safe." -Color DarkRed
            $skippedList += $exePath
            continue
        }

        # --- Create backup if requested ---
        if ($createBackups -eq 'y') {
            $backupPath = "$exePath.backup"
            if (Test-Path $backupPath) {
                Write-VerboseMsg "    ⚠ Backup already exists: $backupPath (skipping)" -Color DarkGray
            } else {
                try {
                    Copy-Item -Path $exePath -Destination $backupPath -Force
                    Write-VerboseMsg "    📁 Backup created: $backupPath" -Color Cyan
                    $backupCreatedCount++
                } catch {
                    Write-VerboseMsg "    ❌ Failed to create backup: $_" -Color Red
                    # Continue anyway – patching might still work
                }
            }
        }

        # Apply patch
        Write-VerboseMsg "    🛠 Attempting to patch: $($exeFile.Name)" -Color Cyan
        try {
            switch ($patcher.Name) {
                "patchlaa" {
                    $cmd = "& `"$($patcher.Path)`" `"$exePath`""
                    Write-VerboseMsg "    Command: $cmd" -Color Gray
                    $output = & $patcher.Path $exePath 2>&1
                    $exitCode = $LASTEXITCODE
                }
                "4gb_patch" {
                    $cmd = "& `"$($patcher.Path)`" `"$exePath`""
                    Write-VerboseMsg "    Command: $cmd" -Color Gray
                    $process = Start-Process -FilePath $patcher.Path -ArgumentList "`"$exePath`"" -NoNewWindow -Wait -PassThru
                    $exitCode = $process.ExitCode
                    $output = $null
                }
                "editbin" {
                    $arguments = "$($patcher.Arguments) `"$exePath`""
                    Write-VerboseMsg "    Command: & `"$($patcher.Path)`" $arguments" -Color Gray
                    Write-VerboseMsg "    Working directory set to: $($patcher.WorkingDirectory)" -Color DarkGray
                    $process = Start-Process -FilePath $patcher.Path -ArgumentList $arguments -NoNewWindow -Wait -PassThru -WorkingDirectory $patcher.WorkingDirectory
                    $exitCode = $process.ExitCode
                    $output = $null
                }
                default { throw "Unknown patcher type: $($patcher.Name)" }
            }

            Write-VerboseMsg "    Patcher output:" -Color Gray
            if ($output) { $output | ForEach-Object { Write-VerboseMsg "      $_" -Color Gray } }
            else { Write-VerboseMsg "      (no output)" -Color Gray }

            if ($exitCode -eq 0) {
                $totalPatched++
                Write-VerboseMsg "    ✅ SUCCESS: $($exeFile.Name) is now Large Address Aware!" -Color Green
            } else {
                throw "Patcher exited with code $exitCode"
            }
        } catch {
            Write-VerboseMsg "    ❌ FAILED: $_" -Color Red
            $failedList += $exePath
        }
    }
}

# Summary
Write-VerboseMsg "`n=== PATCHING COMPLETE ===" -Color Cyan
Write-VerboseMsg "Total .exe files scanned: $totalExeFilesFound" -Color White
Write-VerboseMsg "  - 32-bit executables found: $total32BitExeFiles" -Color Gray
Write-VerboseMsg "  - Successfully patched: $totalPatched" -Color Green
Write-VerboseMsg "  - Skipped (by rules or architecture): $($skippedList.Count)" -Color DarkYellow
Write-VerboseMsg "  - Failed to patch: $($failedList.Count)" -Color $(if ($failedList.Count -gt 0) { "Red" } else { "Green" })
if ($createBackups -eq 'y') {
    Write-VerboseMsg "  - Backups created: $backupCreatedCount" -Color Cyan
}

if ($failedList.Count -gt 0) {
    Write-VerboseMsg "`n--- Failed Executables ---" -Color Red
    $failedList | ForEach-Object { Write-VerboseMsg "  - $_" -Color Red }
}

if ($skippedList.Count -gt 0 -and $skippedList.Count -le 20) {
    Write-VerboseMsg "`n--- Skipped Executables (first 20 shown) ---" -Color DarkYellow
    $skippedList | Select-Object -First 20 | ForEach-Object { Write-VerboseMsg "  - $_" -Color DarkGray }
} elseif ($skippedList.Count -gt 20) {
    Write-VerboseMsg "`n--- $($skippedList.Count) executables were skipped. ---" -Color DarkYellow
}

Write-VerboseMsg "`nScript finished." -Color Cyan
Read-Host "Press Enter to exit"
