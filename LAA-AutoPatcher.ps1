# --- Helper Functions ---
function Write-VerboseMsg {
    param([string]$Message, [string]$Color = "White")
    $timestamp = Get-Date -Format "HH:mm:ss.fff"
    Write-Host "[$timestamp] $Message" -ForegroundColor $Color
}

function Remove-Quotes {
    param([string]$Path)
    if ($Path -match '^"(.+)"$') { return $matches[1] }
    return $Path
}

function Install-patchlaa {
    Write-VerboseMsg "Installing patchlaa via Cargo..." -Color Yellow
    try {
        # Check if cargo command exists
        $cargoExists = Get-Command cargo -ErrorAction SilentlyContinue
        if (-not $cargoExists) {
            Write-VerboseMsg "Cargo (Rust) not found. Do you want to install Rust now?" -Color Cyan
            $installRust = Read-Host "Enter y/n (default: y)"
            if ($installRust -ne 'n') {
                # Try winget first
                $wingetExists = Get-Command winget -ErrorAction SilentlyContinue
                if ($wingetExists) {
                    Write-VerboseMsg "Installing Rust via winget..." -Color Yellow
                    winget install --id=Rustlang.Rustup -e --accept-source-agreements --accept-package-agreements
                    if ($LASTEXITCODE -ne 0) { throw "winget installation failed" }
                } else {
                    # Fallback to direct download
                    Write-VerboseMsg "winget not found. Downloading Rust installer..." -Color Yellow
                    $installerPath = "$env:TEMP\rustup-init.exe"
                    # Ensure TLS 1.2 for older Windows
                    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
                    Invoke-WebRequest -Uri "https://win.rustup.rs/x86_64" -OutFile $installerPath
                    Write-VerboseMsg "Running Rust installer (default options)..." -Color Yellow
                    Start-Process -FilePath $installerPath -ArgumentList "-y" -Wait -NoNewWindow
                    Remove-Item $installerPath -Force -ErrorAction SilentlyContinue
                }
                
                # Refresh PATH and wait a moment for system to register changes
                Write-VerboseMsg "Refreshing environment variables..." -Color Gray
                $env:Path = [System.Environment]::GetEnvironmentVariable("Path","Machine") + ";" + [System.Environment]::GetEnvironmentVariable("Path","User")
                
                # Sometimes PATH takes a moment – retry up to 3 times with delay
                $cargoExists = $null
                for ($i = 1; $i -le 3; $i++) {
                    Start-Sleep -Seconds 2
                    $cargoExists = Get-Command cargo -ErrorAction SilentlyContinue
                    if ($cargoExists) { break }
                }
                
                if (-not $cargoExists) {
                    # Manual check in common Cargo bin paths
                    $cargoPaths = @(
                        "$env:USERPROFILE\.cargo\bin\cargo.exe",
                        "$env:ProgramFiles\Rust stable GNU\bin\cargo.exe",
                        "${env:ProgramFiles(x86)}\Rust stable GNU\bin\cargo.exe"
                    )
                    foreach ($cp in $cargoPaths) {
                        if (Test-Path $cp) {
                            Write-VerboseMsg "Found cargo manually at: $cp" -Color Green
                            $cargoDir = Split-Path $cp -Parent
                            $env:Path = "$cargoDir;$env:Path"
                            $cargoExists = Get-Command cargo -ErrorAction SilentlyContinue
                            break
                        }
                    }
                }
                
                if (-not $cargoExists) {
                    Write-VerboseMsg "Cargo still not found after installation. Please restart PowerShell and run this script again." -Color Red
                    return $false
                }
            } else {
                Write-VerboseMsg "patchlaa installation cancelled." -Color Red
                return $false
            }
        }
        
        Write-VerboseMsg "Cargo found. Installing patchlaa..." -Color Green
        cargo install patchlaa
        if ($LASTEXITCODE -ne 0) { throw "Cargo install failed with exit code $LASTEXITCODE" }
        Write-VerboseMsg "patchlaa installed successfully." -Color Green
        
        # Refresh PATH again to include the new patchlaa.exe
        $env:Path = [System.Environment]::GetEnvironmentVariable("Path","Machine") + ";" + [System.Environment]::GetEnvironmentVariable("Path","User")
        return $true
    } catch {
        Write-VerboseMsg "Failed to install patchlaa: $_" -Color Red
        return $false
    }
}

function Ensure-Patcher {
    param([string]$Choice)
    
    if ($Choice -eq "1") {
        # patchlaa
        $existing = (Get-Command patchlaa.exe -ErrorAction SilentlyContinue).Source
        if ($existing) {
            Write-VerboseMsg "patchlaa found at: $existing" -Color Green
            return @{Path = $existing; Name = "patchlaa"}
        }
        Write-VerboseMsg "patchlaa not found. Attempting to install..." -Color Cyan
        if (Install-patchlaa) {
            $newPath = (Get-Command patchlaa.exe -ErrorAction SilentlyContinue).Source
            if ($newPath) {
                Write-VerboseMsg "patchlaa installed successfully." -Color Green
                return @{Path = $newPath; Name = "patchlaa"}
            } else {
                Write-VerboseMsg "patchlaa installed but not found in PATH. Please restart PowerShell and re‑run the script." -Color Red
                return $null
            }
        }
        return $null
    }
    elseif ($Choice -eq "2") {
        # 4GB Patch
        $existing = (Get-Command 4gb_patch.exe -ErrorAction SilentlyContinue).Source
        if (-not $existing) {
            $commonPaths = @(
                "${env:ProgramFiles}\NTCore\4GB Patch\4gb_patch.exe",
                "${env:ProgramFiles(x86)}\NTCore\4GB Patch\4gb_patch.exe",
                "$env:USERPROFILE\Downloads\4gb_patch.exe"
            )
            foreach ($path in $commonPaths) {
                if (Test-Path $path) { $existing = $path; break }
            }
        }
        if ($existing) {
            Write-VerboseMsg "4GB Patch found at: $existing" -Color Green
            return @{Path = $existing; Name = "4gb_patch"}
        }
        Write-VerboseMsg "`n4GB Patch not found automatically." -Color Yellow
        Write-VerboseMsg "Please enter the full path to 4gb_patch.exe (e.g., C:\Tools\4gb_patch.exe)" -Color White
        Write-VerboseMsg "If you don't have it, you can download it from: https://ntcore.com/4gb-patch/" -Color Gray
        $userPath = Read-Host "Path"
        $userPath = Remove-Quotes $userPath
        if ((Test-Path $userPath) -and ($userPath -like "*.exe")) {
            Write-VerboseMsg "Using 4GB Patch at: $userPath" -Color Green
            return @{Path = $userPath; Name = "4gb_patch"}
        } else {
            Write-VerboseMsg "Invalid path or file not found. Exiting." -Color Red
            return $null
        }
    }
    elseif ($Choice -eq "3") {
        # Microsoft editbin
        Write-VerboseMsg "Searching for Microsoft editbin.exe..." -Color Yellow
        $editbinPaths = @(
            "${env:ProgramFiles}\Microsoft Visual Studio\2022\*\VC\Tools\MSVC\*\bin\Hostx64\x64\editbin.exe",
            "${env:ProgramFiles}\Microsoft Visual Studio\2022\*\VC\Tools\MSVC\*\bin\Hostx86\x86\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2022\*\VC\Tools\MSVC\*\bin\Hostx64\x64\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2022\*\VC\Tools\MSVC\*\bin\Hostx86\x86\editbin.exe",
            "${env:ProgramFiles}\Microsoft Visual Studio\2019\*\VC\Tools\MSVC\*\bin\Hostx64\x64\editbin.exe",
            "${env:ProgramFiles}\Microsoft Visual Studio\2019\*\VC\Tools\MSVC\*\bin\Hostx86\x86\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2019\*\VC\Tools\MSVC\*\bin\Hostx64\x64\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2019\*\VC\Tools\MSVC\*\bin\Hostx86\x86\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2017\*\VC\Tools\MSVC\*\bin\Hostx64\x64\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2017\*\VC\Tools\MSVC\*\bin\Hostx86\x86\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio 10.0\VC\bin\editbin.exe",
            "${env:ProgramFiles(x86)}\Microsoft Visual Studio 10.0\VC\bin\amd64\editbin.exe",
            (Get-Command editbin.exe -ErrorAction SilentlyContinue).Source
        )
        $existing = $null
        foreach ($pathPattern in $editbinPaths) {
            $resolvedPaths = Resolve-Path $pathPattern -ErrorAction SilentlyContinue
            foreach ($resolvedPath in $resolvedPaths) {
                if (Test-Path $resolvedPath) { $existing = $resolvedPath.Path; break }
            }
            if ($existing) { break }
        }
        if ($existing) {
            Write-VerboseMsg "Microsoft editbin found at: $existing" -Color Green
            $editbinDir = Split-Path $existing -Parent
            Write-VerboseMsg "Note: editbin may require VC runtime DLLs. Working directory will be set to $editbinDir" -Color DarkGray
            return @{Path = $existing; Name = "editbin"; Arguments = "/LARGEADDRESSAWARE /NOLOGO"; WorkingDirectory = $editbinDir}
        } else {
            Write-VerboseMsg "`nMicrosoft editbin.exe not found." -Color Red
            Write-VerboseMsg "This tool is part of Visual Studio Build Tools or Visual Studio." -Color Yellow
            Write-VerboseMsg "You can install the free Visual Studio Community or Build Tools from:" -Color Yellow
            Write-VerboseMsg "https://visualstudio.microsoft.com/downloads/" -Color Cyan
            Write-VerboseMsg "Make sure to select the 'C++ build tools' workload during installation." -Color Yellow
            Write-VerboseMsg "Alternatively, you can manually provide the full path." -Color Gray
            $userPath = Read-Host "Enter full path to editbin.exe (or press Enter to cancel)"
            if ($userPath) {
                $userPath = Remove-Quotes $userPath
                if (Test-Path $userPath) {
                    Write-VerboseMsg "Using editbin at: $userPath" -Color Green
                    $editbinDir = Split-Path $userPath -Parent
                    return @{Path = $userPath; Name = "editbin"; Arguments = "/LARGEADDRESSAWARE /NOLOGO"; WorkingDirectory = $editbinDir}
                } else {
                    Write-VerboseMsg "File not found. Exiting." -Color Red
                    return $null
                }
            } else {
                Write-VerboseMsg "editbin selection cancelled. Exiting." -Color Red
                return $null
            }
        }
    }
    else {
        Write-VerboseMsg "Invalid patcher choice. Exiting." -Color Red
        return $null
    }
}

# --- Main Script ---
Write-VerboseMsg "=== Powershell LAA Autopatcher ===" -Color Cyan

# --- Patcher Selection ---
